const REVIEW_FROZEN_AT = '2026-08-24T03:30:00.000Z';

interface EvidenceInput {
  readonly sourceId: string;
  readonly title: string;
  readonly publisher: string;
  readonly url: string;
  readonly publishedAt: string;
  readonly level: EvidenceLevel;
  readonly language?: 'zh' | 'en';
  readonly dateBasis?: EvidenceRef['dateBasis'];
}

interface SupportingFactInput {
  readonly statement: string;
  readonly evidenceIndexes: readonly number[];
}

interface CandidateInput {
  readonly id: string;
  readonly slug: string;
  readonly seedCategory: SeedContentCategory;
  readonly conclusionScope: ConclusionScope;
  readonly title: string;
  readonly originalTitle?: string;
  readonly summary: string;
  readonly kind: SeedCandidate['kind'];
  readonly domains: readonly KnowledgeDomain[];
  readonly topicSlugs: readonly string[];
  readonly tags: readonly string[];
  readonly toolIds: readonly string[];
  readonly audience?: SeedCandidate['audience'];
  readonly publishedAt: string;
  readonly freshness: SeedCandidate['freshness'];
  readonly whyItMatters: string;
  readonly salesImplication: string;
  readonly roleOrgImplication: string;
  readonly nextAction: string;
  readonly evidence: readonly EvidenceInput[];
  readonly supportingFacts: readonly SupportingFactInput[];
  readonly deeperAnalysis: DeeperAnalysis;
  readonly riskLevel: RiskLevel;
  readonly changeWindow: SeedReview['changeWindow'];
  readonly factType: SeedReview['factType'];
  readonly verificationNotes: string;
}

function defineCandidate(input: CandidateInput): SeedCandidate {
  const evidence = input.evidence.map((item, index) => ({
    id: `${input.id}-e${index + 1}`,
    sourceId: item.sourceId,
    title: item.title,
    publisher: item.publisher,
    url: item.url,
    publishedAt: item.publishedAt,
    level: item.level,
    language: item.language ?? 'en',
    allowlisted: true,
    dateBasis: item.dateBasis ?? 'published',
  }));

  return {
    id: input.id,
    slug: input.slug,
    seedCategory: input.seedCategory,
    conclusionScope: input.conclusionScope,
    supportingFacts: input.supportingFacts.map((fact, index) => ({
      id: `${input.id}-f${index + 1}`,
      statement: fact.statement,
      evidenceIds: fact.evidenceIndexes.map((evidenceIndex) => `${input.id}-e${evidenceIndex}`),
    })),
    deeperAnalysis: input.deeperAnalysis,
    title: { zh: input.title },
    originalTitle: input.originalTitle,
    summary: { zh: input.summary },
    kind: input.kind,
    domains: input.domains,
    topicSlugs: input.topicSlugs,
    tags: input.tags,
    toolIds: input.toolIds,
    audience: input.audience ?? ['transitioning_seller', 'ai_ae', 'solution'],
    publishedAt: input.publishedAt,
    updatedAt: REVIEW_FROZEN_AT,
    freshness: input.freshness,
    whyItMatters: { zh: input.whyItMatters },
    salesImplication: { zh: input.salesImplication },
    roleOrgImplication: { zh: input.roleOrgImplication },
    nextAction: { zh: input.nextAction },
    evidence,
    relatedItemIds: [],
    editorialStatus: 'candidate',
    riskLevel: input.riskLevel,
    publicationMode: 'manual',
    seedContent: true,
    audit: {
      sourceFingerprint: `source-ref:${input.slug}:2026-08-24`,
      ruleVersion: 'saas-602-seed-review-v2',
      processedAt: REVIEW_FROZEN_AT,
      releaseVersion: 'seed-review-v2-2026-08-24',
      rollbackState: 'available',
    },
    review: {
      status: 'pending_owner_review',
      verifiedAt: REVIEW_FROZEN_AT,
      changeWindow: input.changeWindow,
      factType: input.factType,
      verificationNotes: input.verificationNotes,
    },
  };
}

